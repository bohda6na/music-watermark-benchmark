"""Compare watermarking methods: read all results CSVs and build the comparison tables.

    python -m scripts.compare_methods                       # results/results_*.csv
    python -m scripts.compare_methods results/results_audioseal.csv results/results_wavmark.csv

By default every results/results_*.csv is used, except the separate --detect-speed
experiment (pass its file explicitly to include it). Needs only the CSV files, no audio.

Scores (each one is a share of tracks, so 0.64 = 51 of 80):
- message read: the 16-bit message is decoded with at least 14 correct bits (`detected`);
  the 95% interval is the Wilson score interval;
- watermark found: the method's own detector says "watermarked" (detect_prob > 0.5);
  only for methods that have such a detector (AudioSeal), otherwise "-";
- mean bits: mean number of correct bits out of 16. When a method returns no message at
  all (audiowmark, WavMark), the track counts as 8 of 16, i.e. chance level.

Outputs (folder set by --out-dir, default results/summary):
- comparison.md: the tables below, ready to paste into a README;
- by_attack.csv: method x attack x params with all scores;
- by_genre.csv: the same split by genre.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import pandas as pd

from attacks import all_attacks

CHANCE_BIT_ACC = 0.5
CONTROL = "unwatermarked"
Z95 = 1.96


# ---------- helpers ----------


def fmt(v: float | None, digits: int = 2) -> str:
    """Round half up (0.075 -> 0.08), '-' for missing values."""
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "-"
    k = 10**digits
    return f"{math.floor(v * k + 0.5) / k:.{digits}f}"


def wilson(k: int, n: int, z: float = Z95) -> tuple[float, float]:
    """95% Wilson score interval for a share k/n."""
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    d = 1 + z**2 / n
    c = (p + z**2 / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / d
    return max(0.0, c - h), min(1.0, c + h)


def md_table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def attack_order() -> dict[tuple[str, str], int]:
    """Position of each (attack, params) in the shared attack list, for sorting."""
    keys = [(CONTROL, "-")] + [(a, p) for a, p, _ in all_attacks(include_neural=True)]
    return {k: i for i, k in enumerate(keys)}


# ---------- loading ----------


def load(paths: list[Path]) -> pd.DataFrame:
    frames = []
    for path in paths:
        d = pd.read_csv(path, dtype={"params": str}, keep_default_na=False)
        d["source"] = path.name
        frames.append(d)
    d = pd.concat(frames, ignore_index=True)

    dup = d.duplicated(["method", "track_id", "attack", "params"])
    if dup.any():
        print(f"warning: {dup.sum()} duplicate rows, keeping the first of each")
        d = d[~dup]

    d["msg"] = d["detected"].astype(str).str.lower().isin({"1", "true"}).astype(int)
    prob = pd.to_numeric(d["detect_prob"], errors="coerce")
    d["found"] = (prob > 0.5).astype(float).where(prob.notna())
    d["bits"] = 16 * pd.to_numeric(d["bit_acc"], errors="coerce").fillna(CHANCE_BIT_ACC)
    d["snr"] = pd.to_numeric(d["snr"], errors="coerce")
    return d


def summarize(d: pd.DataFrame, by: list[str]) -> pd.DataFrame:
    g = d.groupby(by, sort=False)
    s = g.agg(
        n=("msg", "size"),
        k=("msg", "sum"),
        message_read=("msg", "mean"),
        watermark_found=("found", "mean"),
        mean_bits=("bits", "mean"),
    ).reset_index()
    ci = [wilson(int(k), int(n)) for k, n in zip(s["k"], s["n"])]
    s.insert(s.columns.get_loc("message_read") + 1, "ci_low", [c[0] for c in ci])
    s.insert(s.columns.get_loc("ci_low") + 1, "ci_high", [c[1] for c in ci])
    return s.drop(columns="k")


# ---------- report ----------


def report(d: pd.DataFrame) -> tuple[str, pd.DataFrame, pd.DataFrame]:
    methods = list(dict.fromkeys(d["method"]))
    order = attack_order()
    by_attack = summarize(d, ["method", "attack", "params"])
    by_attack["_o"] = [
        order.get((a, p), len(order)) for a, p in zip(by_attack.attack, by_attack.params)
    ]
    by_attack = by_attack.sort_values(["_o", "method"]).drop(columns="_o")
    by_genre = summarize(d, ["method", "attack", "params", "genre"])

    idx = by_attack.set_index(["method", "attack", "params"])
    keys = list(dict.fromkeys(zip(by_attack.attack, by_attack.params)))
    has_found = [m for m in methods if d.loc[d.method == m, "found"].notna().any()]
    n_tracks = d.groupby("method")["track_id"].nunique()

    out = ["# Method comparison", ""]
    out.append(
        "Generated by `python -m scripts.compare_methods` from: "
        + ", ".join(f"`{s}`" for s in dict.fromkeys(d["source"]))
        + ". Tracks per method: "
        + ", ".join(f"{m} {n_tracks[m]}" for m in methods)
        + "."
    )

    # 1. robustness: message read per method, + watermark found where available
    out += ["", "## Robustness: share of tracks", ""]
    out.append(
        "Message read = at least 14 of 16 bits correct; [95% interval]. "
        "Watermark found = the method's own detector (detect_prob > 0.5). "
        "'-' = attack not run for this method."
    )
    header = ["Attack", "Params"] + [f"{m}: message read" for m in methods]
    header += [f"{m}: watermark found" for m in has_found]
    rows = []
    for a, p in keys:
        if a == CONTROL:
            continue
        r = [a, p]
        for m in methods:
            if (m, a, p) in idx.index:
                s = idx.loc[(m, a, p)]
                r.append(f"{fmt(s.message_read)} [{fmt(s.ci_low)}-{fmt(s.ci_high)}]")
            else:
                r.append("-")
        for m in has_found:
            r.append(fmt(idx.loc[(m, a, p)].watermark_found) if (m, a, p) in idx.index else "-")
        rows.append(r)
    out.append("")
    out.append(md_table(header, rows))

    # 2. mean correct bits
    out += ["", "## Mean correct bits (of 16)", ""]
    out.append("No message returned counts as 8 (chance).")
    out.append("")
    rows = [
        [a, p]
        + [fmt(idx.loc[(m, a, p)].mean_bits, 1) if (m, a, p) in idx.index else "-" for m in methods]
        for a, p in keys
    ]
    out.append(md_table(["Attack", "Params"] + methods, rows))

    # 3. false positives
    out += ["", "## False positives (unwatermarked tracks)", ""]
    rows = []
    for m in methods:
        if (m, CONTROL, "-") in idx.index:
            s = idx.loc[(m, CONTROL, "-")]
            rows.append(
                [m, str(int(s.n)), fmt(s.message_read), fmt(s.watermark_found), fmt(s.mean_bits, 1)]
            )
    out.append(md_table(["Method", "Tracks", "Message read", "Watermark found", "Mean bits"], rows))

    # 4. quality
    out += ["", "## Audio quality: SNR after embedding (dB, no attack)", ""]
    base = d[d.attack == "none"]
    genres = sorted(base["genre"].unique())
    q = base.groupby("method")["snr"].agg(["mean", "min", "max"])
    qg = base.groupby(["method", "genre"])["snr"].mean()
    rows = [
        [m, fmt(q.loc[m, "mean"], 1), fmt(q.loc[m, "min"], 1), fmt(q.loc[m, "max"], 1)]
        + [fmt(qg.get((m, g)), 1) for g in genres]
        for m in methods
        if m in q.index
    ]
    out.append(md_table(["Method", "Mean", "Min", "Max"] + genres, rows))

    # 5. genres: no attack + mean over the attacks that every method was tested with
    attacked = [k for k in keys if k[0] not in ("none", CONTROL)]
    common = [k for k in attacked if all((m, *k) in idx.index for m in methods)]
    out += ["", "## Message read by genre", ""]
    out.append(
        f"'none' = no attack; 'attacks' = mean over the {len(common)} attack variants "
        "that every method was tested with, so the methods are compared on the same set."
    )
    out.append("")
    gs = d[d.attack != CONTROL].copy()
    gs["is_common"] = [(a, p) in set(common) for a, p in zip(gs.attack, gs.params)]
    none_g = gs[gs.attack == "none"].groupby(["method", "genre"])["msg"].mean()
    att_g = gs[gs.is_common].groupby(["method", "genre"])["msg"].mean()
    header = ["Genre"]
    for m in methods:
        header += [f"{m}: none", f"{m}: attacks"]
    rows = []
    for g in genres:
        r = [g]
        for m in methods:
            r += [fmt(none_g.get((m, g))), fmt(att_g.get((m, g)))]
        rows.append(r)
    out.append(md_table(header, rows))
    n_genre = base.groupby(["method", "genre"]).size()
    lo, hi = int(n_genre.min()), int(n_genre.max())
    out.append("")
    out.append(
        f"Tracks per genre: {lo if lo == hi else f'{lo}-{hi}'}. With n tracks one track moves "
        "a value by 1/n (0.1 for 10 tracks), so genre differences are preliminary."
    )

    return "\n".join(out) + "\n", by_attack, by_genre


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("csv", nargs="*", type=Path, help="results CSV files")
    p.add_argument("--out-dir", type=Path, default=Path("results/summary"))
    args = p.parse_args(argv)

    paths = args.csv or sorted(
        f for f in Path("results").glob("results_*.csv") if "detect_speed" not in f.name
    )
    if not paths:
        p.error("no results CSV files found")

    md, by_attack, by_genre = report(load(paths))
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "comparison.md").write_text(md, encoding="utf-8")
    for name, t in (("by_attack.csv", by_attack), ("by_genre.csv", by_genre)):
        t.round(4).to_csv(args.out_dir / name, index=False)
    print(md)
    print(f"saved -> {args.out_dir}/comparison.md, by_attack.csv, by_genre.csv")


if __name__ == "__main__":
    main()
